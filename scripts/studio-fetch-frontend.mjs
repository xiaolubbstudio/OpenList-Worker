import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const stage = path.join(root, '.frontend-artifact');
fs.mkdirSync(stage, { recursive: true });
const metaResponse = await fetch('https://registry.npmjs.org/@openlist-frontend/openlist-frontend/4.2.6');
if (!metaResponse.ok) throw new Error('Official frontend metadata unavailable');
const meta = await metaResponse.json();
const url = new URL(meta.dist.tarball);
if (url.protocol !== 'https:' || url.hostname !== 'registry.npmjs.org') throw new Error('Unexpected frontend registry');
const response = await fetch(url);
if (!response.ok) throw new Error('Official frontend download failed');
const bytes = Buffer.from(await response.arrayBuffer());
const integrity = 'sha512-' + crypto.createHash('sha512').update(bytes).digest('base64');
if (integrity !== meta.dist.integrity) throw new Error('Frontend integrity verification failed');
const archive = path.join(stage, 'frontend.tgz');
fs.writeFileSync(archive, bytes);
const names = execFileSync('tar', ['-tzf', archive], { encoding: 'utf8' }).split(/\r?\n/);
if (names.some(n => n.startsWith('/') || /^[a-zA-Z]:/.test(n) || n.split('/').includes('..'))) throw new Error('Unsafe archive path');
execFileSync('tar', ['-xzf', archive, '-C', stage, 'package/dist', 'package/package.json']);
fs.cpSync(path.join(stage, 'package/dist'), path.join(root, 'dist'), { recursive: true });
console.log('Official frontend 4.2.6 ready; initial admin must be configured through ADMIN_PASS.');
